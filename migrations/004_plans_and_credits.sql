CREATE TABLE plans (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barber_id     INTEGER NOT NULL REFERENCES barbers(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  price_kobo    INTEGER NOT NULL CHECK (price_kobo > 0),
  sessions      INTEGER NOT NULL CHECK (sessions > 0),
  validity_days INTEGER NOT NULL CHECK (validity_days > 0),
  active        BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_plans_barber ON plans (barber_id) WHERE active;

CREATE TABLE plan_services (
  plan_id    INTEGER NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
  service_id INTEGER NOT NULL REFERENCES services(id),
  PRIMARY KEY (plan_id, service_id)
);

-- One row per purchase. Everything a booking needs is snapshotted, so later plan edits never change what a customer already bought.
-- PENDING = checkout started, not paid: invisible to the barber (same rule as unpaid Pay-now bookings). ACTIVE = paid.
CREATE TABLE plan_purchases (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id        INTEGER NOT NULL REFERENCES plans(id),
  customer_id    INTEGER NOT NULL REFERENCES users(id),
  barber_id      INTEGER NOT NULL REFERENCES barbers(id),
  plan_name      TEXT NOT NULL,
  price_kobo     INTEGER NOT NULL CHECK (price_kobo > 0),
  sessions_total INTEGER NOT NULL CHECK (sessions_total > 0),
  sessions_used  INTEGER NOT NULL DEFAULT 0,
  validity_days  INTEGER NOT NULL,
  service_ids    INTEGER[] NOT NULL,
  status         TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACTIVE')),
  paid_at        TIMESTAMPTZ,
  expires_at     TIMESTAMPTZ,                                 -- set on payment: paid_at + validity_days. Sessions die with the plan.
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT sessions_within_total CHECK (sessions_used >= 0 AND sessions_used <= sessions_total)
);
CREATE INDEX idx_purchases_customer ON plan_purchases (customer_id, barber_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_purchases_barber   ON plan_purchases (barber_id) WHERE status = 'ACTIVE';

-- A missed paid session becomes ONE credit with the SAME barber. Never cashable. Expiry is enforced by expires_at checks (lazy).
CREATE TABLE session_credits (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id       INTEGER NOT NULL REFERENCES users(id),
  barber_id         INTEGER NOT NULL REFERENCES barbers(id),
  source_booking_id INTEGER UNIQUE REFERENCES bookings(id),   -- UNIQUE: a missed booking can only ever produce one credit
  reason            TEXT NOT NULL,                            -- NO_SHOW | LATE_CANCEL | EARLY_CANCEL
  value_kobo        INTEGER NOT NULL CHECK (value_kobo >= 0), -- usable for any service of that barber priced up to this
  status            TEXT NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','USED')),
  expires_at        TIMESTAMPTZ NOT NULL,
  used_booking_id   INTEGER REFERENCES bookings(id),
  used_at           TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_credits_customer ON session_credits (customer_id, barber_id, expires_at) WHERE status = 'AVAILABLE';
CREATE INDEX idx_credits_barber   ON session_credits (barber_id, created_at DESC);

