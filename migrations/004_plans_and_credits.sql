-- Subscriptions (barber plans / session packs) and same-barber session credits.

-- Platform-wide rules, ONE row (id = 1). Edited only through the admin CLI / admin API. Barbers can never go outside these limits.
CREATE TABLE platform_settings (
  id                           SMALLINT PRIMARY KEY CHECK (id = 1),
  min_plan_price_kobo          INTEGER NOT NULL DEFAULT 100000    CHECK (min_plan_price_kobo >= 0),       -- NGN 1,000
  max_plan_price_kobo          INTEGER NOT NULL DEFAULT 50000000  CHECK (max_plan_price_kobo >= 0),       -- NGN 500,000
  max_plan_validity_days       INTEGER NOT NULL DEFAULT 90        CHECK (max_plan_validity_days BETWEEN 1 AND 730),
  max_plan_sessions            INTEGER NOT NULL DEFAULT 30        CHECK (max_plan_sessions BETWEEN 1 AND 500),
  platform_fee_percent         NUMERIC(5,2) NOT NULL DEFAULT 0    CHECK (platform_fee_percent BETWEEN 0 AND 100),
  platform_fee_kobo            INTEGER NOT NULL DEFAULT 0         CHECK (platform_fee_kobo >= 0),         -- flat part; 0/0 => falls back to PLATFORM_FEE_* env vars
  credit_expiry_days           INTEGER NOT NULL DEFAULT 30        CHECK (credit_expiry_days BETWEEN 1 AND 365),
  -- refund rules. Credits are never cashable and nothing is ever auto-refunded to a card.
  credit_on_missed_session     BOOLEAN NOT NULL DEFAULT TRUE,     -- no-show / late cancel of a paid session => 1 credit with the same barber
  credit_on_early_cancel_prepaid BOOLEAN NOT NULL DEFAULT FALSE,  -- in-time cancel of a prepaid (online) booking => credit (default: stays CREDIT_PENDING for manual follow-up, as before)
  plan_refund_policy           TEXT NOT NULL DEFAULT 'NONE' CHECK (plan_refund_policy IN ('NONE','MANUAL')), -- unused sessions: no refund / case-by-case (shown to buyers)
  updated_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT plan_price_range CHECK (min_plan_price_kobo <= max_plan_price_kobo)
);
