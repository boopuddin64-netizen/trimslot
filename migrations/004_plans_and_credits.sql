-- ---------------------------------------------------------------------------------------------------------------
-- Incomplete-booking rule, tightened: an UNPAID Pay-now attempt (PENDING_PAYMENT) no longer reserves ANY slot.
-- Only complete bookings (paid online, pay-on-arrival, plan/credit) occupy the calendar, so both DB-level guards
-- drop PENDING_PAYMENT. Payment confirmation re-checks the slot under the barber row lock (see applyVerifiedPayment).
-- ---------------------------------------------------------------------------------------------------------------
DROP INDEX IF EXISTS uq_bookings_active_slot;
CREATE UNIQUE INDEX uq_bookings_active_slot ON bookings (barber_id, scheduled_at)
  WHERE status IN ('CONFIRMED','ARRIVED','IN_SERVICE','COMPLETED');
ALTER TABLE bookings DROP CONSTRAINT IF EXISTS bookings_no_overlap;
DO $$
BEGIN
  BEGIN
    CREATE EXTENSION IF NOT EXISTS btree_gist;
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'btree_gist unavailable (%): skipping bookings_no_overlap exclusion constraint', SQLERRM;
    RETURN;
  END;
  ALTER TABLE bookings
    ADD CONSTRAINT bookings_no_overlap
    EXCLUDE USING gist (barber_id WITH =, tstzrange(scheduled_at, ends_at) WITH &&)
    WHERE (status IN ('CONFIRMED','ARRIVED','IN_SERVICE','COMPLETED'));
END
$$;

