-- 008: web push, smart customer/barber features (all behind admin toggles), and admin list performance indexes.

/* ---------- web push ---------- */
CREATE TABLE push_subscriptions (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  endpoint     TEXT NOT NULL UNIQUE,
  p256dh       TEXT NOT NULL,
  auth         TEXT NOT NULL,
  user_agent   TEXT,
  failures     INTEGER NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_ok_at   TIMESTAMPTZ
);
CREATE INDEX idx_push_user ON push_subscriptions (user_id);
ALTER TABLE push_subscriptions ENABLE ROW LEVEL SECURITY;

-- Every notification is pushed exactly once: NULL = not pushed yet. Rows that already exist are marked done so nobody gets old news.
ALTER TABLE notifications ADD COLUMN pushed_at TIMESTAMPTZ;
UPDATE notifications SET pushed_at = now();
CREATE INDEX idx_notif_unpushed ON notifications (id) WHERE pushed_at IS NULL;

/* ---------- smart features ---------- */
ALTER TABLE bookings ADD COLUMN note_to_barber TEXT;
ALTER TABLE bookings ADD COLUMN rem2h_at  TIMESTAMPTZ;
ALTER TABLE bookings ADD COLUMN rem30_at  TIMESTAMPTZ;
ALTER TABLE bookings ADD COLUMN leave_at  TIMESTAMPTZ;
ALTER TABLE barbers  ADD COLUMN delay_min  INTEGER NOT NULL DEFAULT 0 CHECK (delay_min BETWEEN 0 AND 240);
ALTER TABLE barbers  ADD COLUMN delay_date DATE;

CREATE TABLE favourites (
  customer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  barber_id   INTEGER NOT NULL REFERENCES barbers(id) ON DELETE CASCADE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (customer_id, barber_id)
);
CREATE INDEX idx_favourites_barber ON favourites (barber_id);

CREATE TABLE waitlist (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES users(id),
  barber_id   INTEGER NOT NULL REFERENCES barbers(id),
  service_id  INTEGER NOT NULL REFERENCES services(id),
  date        DATE NOT NULL,
  status      TEXT NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING','NOTIFIED','BOOKED','CANCELLED','EXPIRED')),
  notified_at TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_waitlist_active ON waitlist (customer_id, barber_id, date) WHERE status IN ('WAITING','NOTIFIED');
CREATE INDEX idx_waitlist_barber_date ON waitlist (barber_id, date) WHERE status IN ('WAITING','NOTIFIED');

CREATE TABLE reviews (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id  INTEGER NOT NULL UNIQUE REFERENCES bookings(id),
  customer_id INTEGER NOT NULL REFERENCES users(id),
  barber_id   INTEGER NOT NULL REFERENCES barbers(id),
  rating      SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment     TEXT CHECK (comment IS NULL OR length(comment) <= 500),
  reply       TEXT CHECK (reply IS NULL OR length(reply) <= 500),
  replied_at  TIMESTAMPTZ,
  hidden      BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reviews_barber ON reviews (barber_id, id DESC) WHERE NOT hidden;
CREATE INDEX idx_reviews_customer ON reviews (customer_id);

CREATE TABLE barber_customer_notes (
  barber_id   INTEGER NOT NULL REFERENCES barbers(id) ON DELETE CASCADE,
  customer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  note        TEXT NOT NULL CHECK (length(note) <= 1000),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (barber_id, customer_id)
);
ALTER TABLE favourites ENABLE ROW LEVEL SECURITY;
ALTER TABLE waitlist ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE barber_customer_notes ENABLE ROW LEVEL SECURITY;

