/* ---------- admin list performance (keyset pagination + filters + search) ---------- */
-- Fuzzy search indexes need pg_trgm; if the role cannot create it the migration still succeeds (search falls back to a sequential scan).
DO $$
BEGIN
  BEGIN
    CREATE EXTENSION IF NOT EXISTS pg_trgm;
    CREATE INDEX idx_users_name_trgm   ON users USING gin (lower(name) gin_trgm_ops);
    CREATE INDEX idx_users_email_trgm  ON users USING gin (lower(email) gin_trgm_ops);
    CREATE INDEX idx_users_phone_trgm  ON users USING gin (phone gin_trgm_ops);
    CREATE INDEX idx_barbers_shop_trgm ON barbers USING gin (lower(shop_name) gin_trgm_ops);
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'pg_trgm search indexes skipped: %', SQLERRM;
  END;
END $$;
