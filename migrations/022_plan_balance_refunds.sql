-- 022: plan balance refunds. A plan can be cancelled part-way ONLY by a joint request: the customer and the barber both confirm,
-- then an admin authorizes it. The refund is the unused sessions' share of the plan price (no Paystack fee). Additive only.

CREATE TABLE plan_refund_requests (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_purchase_id    INTEGER NOT NULL REFERENCES plan_purchases(id),
  requested_by        INTEGER NOT NULL REFERENCES users(id),
  requested_role      TEXT NOT NULL CHECK (requested_role IN ('CUSTOMER','BARBER')),
  amount_kobo         INTEGER NOT NULL CHECK (amount_kobo > 0),
  sessions_left       INTEGER NOT NULL CHECK (sessions_left > 0),
  status              TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CONFIRMED','REFUNDING','REFUNDED','WITHDRAWN')),
  customer_confirmed_at TIMESTAMPTZ,
  barber_confirmed_at   TIMESTAMPTZ,
  refund_error        TEXT,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at          TIMESTAMPTZ
);

-- one live request per plan (open, confirmed or refunding)
CREATE UNIQUE INDEX one_live_plan_refund ON plan_refund_requests (plan_purchase_id) WHERE status IN ('OPEN','CONFIRMED','REFUNDING');

-- the amount sent to Paystack when it is not the whole payment
ALTER TABLE payments ADD COLUMN refund_amount_kobo INTEGER;
